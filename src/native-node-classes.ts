const NODE_CLASS_BY_LOWER: ReadonlyMap<string, string> = new Map(
  [...NATIVE_NODE_CLASSES].map((name) => [name.toLowerCase(), name])
);

/** True if `name` is a ClassDB Node type that can be instantiated as a scene root. */
export function isNativeNodeClass(name: string): boolean {
  return NATIVE_NODE_CLASSES.has(name);
}

/** True if `name` is a known ClassDB class that is not a Node. */
export function isNativeNonNodeClass(name: string): boolean {
  return NATIVE_NON_NODE_CLASSES.has(name);
}

/** If `name` matches a Node class ignoring case only, return the canonical name. */
export function suggestNativeNodeClass(name: string): string | undefined {
  if (!name || NATIVE_NODE_CLASSES.has(name)) {
    return undefined;
  }
  return NODE_CLASS_BY_LOWER.get(name.toLowerCase());
}

/**
 * Error text for an invalid create_scene root_node_type (caller still refuses / writes nothing).
 * Empty → required; case-only mismatch → suggestion; known non-Node → not a Node type; else unknown.
 */
export function invalidRootNodeTypeMessage(rootNodeType: string): string {
  if (!rootNodeType.trim()) {
    return "root_node_type is required";
  }
  const suggestion = suggestNativeNodeClass(rootNodeType);
  if (suggestion) {
    return `Unknown node type: ${rootNodeType}. Did you mean ${suggestion}?`;
  }
  if (isNativeNonNodeClass(rootNodeType)) {
    return `${rootNodeType} is not a Node type`;
  }
  return `Unknown node type: ${rootNodeType}`;
}
